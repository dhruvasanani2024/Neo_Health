// Helper function to get medications by category
export const getMedicationsByCategory = (category) => {
    if (!category || category === 'All') return medications
    return medications.filter(med => med.category === category)
}

// Helper function to search medications
export const searchMedications = (query) => {
    if (!query) return medications
    const lowerQuery = query.toLowerCase()
    return medications.filter(med => 
        med.name.toLowerCase().includes(lowerQuery) ||
        med.description.toLowerCase().includes(lowerQuery) ||
        med.category.toLowerCase().includes(lowerQuery)
    )
}
